#!/usr/bin/env python3
"""
Write apps/README.md: every app in the gallery as one row of a table - its
preview, name, what it does, author and tags - read from the apps' own
manifest.yaml files, so GitHub shows the gallery when you open apps/.

    npm run index                  # or: python3 tools/apps_index.py
    python3 tools/apps_index.py --check   # exit 1 if apps/README.md is stale

The Apps index workflow runs it after every push to main and commits the file
when it changed, so a submission needs no edit to it. The output depends only
on the apps, never on the date, so an unchanged gallery rewrites nothing.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from busycheck import parse_manifest  # noqa: E402 - the same reading busycheck does

ROOT = Path(__file__).resolve().parent.parent
APPS = ROOT / "apps"
OUT = APPS / "README.md"
SITE = "https://maxswinkels.github.io/busybar-apps"
PREVIEW_WIDTH = 288  # of 720: four previews' worth of rows per screen

HEADER = """\
# Apps

<!-- Generated by tools/apps_index.py from each app's manifest.yaml.
     Do not edit: the Apps index workflow rewrites this file after every
     push to main. -->

All {count} apps in the gallery, A to Z. Each has a page in the
[live gallery]({site}/) with its preview at full size, and a folder here
with its code. *zero-install* apps need only Python: they have no
`requirements.txt`.

| Preview | App | What it does | Tags |
| --- | --- | --- | --- |
"""


def cell(text):
    """Text that cannot break a table row."""
    return " ".join(str(text).split()).replace("|", "\\|")


def attribute(text):
    return cell(text).replace("&", "&amp;").replace('"', "&quot;")


def apps():
    """(slug, manifest, zero-install) for every folder with a manifest.yaml."""
    for folder in sorted(APPS.iterdir()):
        manifest = folder / "manifest.yaml"
        if folder.is_dir() and manifest.is_file():
            data = parse_manifest(manifest.read_text(encoding="utf-8"))
            yield folder.name, data, not (folder / "requirements.txt").exists()


def row(slug, data, zero_install):
    name = data.get("name") or slug
    preview = str(data.get("preview") or "").removeprefix("./")
    picture = (
        f'<a href="{slug}/"><img src="{slug}/{preview}" width="{PREVIEW_WIDTH}" '
        f'alt="{attribute(name)}"></a>'
        if preview
        else ""
    )
    author = data.get("author")
    app = f"[**{cell(name)}**]({slug}/)"
    if author:
        app += f"<br>by [@{cell(author)}](https://github.com/{cell(author)})"
    app += f"<br>[gallery page]({SITE}/apps/{slug}/)"
    if zero_install:
        app += "<br>*zero-install*"
    tags = data.get("tags") or []
    if isinstance(tags, str):
        tags = [tags]
    tag_text = " ".join(f"`{cell(tag)}`" for tag in tags)
    return f"| {picture} | {app} | {cell(data.get('description') or '')} | {tag_text} |"


def render():
    found = sorted(apps(), key=lambda item: str(item[1].get("name") or item[0]).lower())
    lines = [HEADER.format(count=len(found), site=SITE)]
    lines += [row(*item) for item in found]
    return "".join(lines[:1]) + "\n".join(lines[1:]) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description="Write the apps index, apps/README.md.")
    parser.add_argument(
        "--check", action="store_true", help="exit 1 when apps/README.md is out of date"
    )
    args = parser.parse_args(argv)
    text = render()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if args.check:
        if current != text:
            print("apps/README.md is out of date: run npm run index", file=sys.stderr)
            return 1
        print("apps/README.md is up to date")
        return 0
    if current == text:
        print("apps/README.md is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote apps/README.md: {sum(1 for _ in apps())} apps")
    return 0


if __name__ == "__main__":
    sys.exit(main())
